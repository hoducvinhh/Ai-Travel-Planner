async function main() {
  console.log(`🚀 Bắt đầu thêm 240 địa điểm mới (nâng lên 40 địa điểm/tỉnh cho 8 tỉnh)...`);

  let added = 0;
  let skipped = 0;

  for (const place of EXPANDED_PLACES) {
    // Kiểm tra trùng lặp theo tên hoặc tọa độ rất gần
    const existing = await prisma.place.findFirst({
      where: {
        OR: [
          { name: { equals: place.name, mode: 'insensitive' } },
        ],
      },
    });

    if (existing) {
      console.log(`⚠️ Đã tồn tại: "${place.name}" (${place.province}) -> Bỏ qua.`);
      skipped++;
      continue;
    }

    await prisma.place.create({
      data: {
        name: place.name,
        description: place.description,
        categories: place.categories,
        latitude: place.latitude,
        longitude: place.longitude,
        province: place.province,
        district: place.district,
        priceEstimate: place.priceEstimate,
        popularityScore: place.popularityScore,
        indoorOutdoor: place.indoorOutdoor,
        activityLevel: place.activityLevel,
      },
    });
    added++;
  }

  console.log(`\n🎉 HOÀN THÀNH SEED BỔ SUNG!`);
  console.log(`✅ Đã thêm mới: ${added} địa điểm.`);
  console.log(`⏩ Đã bỏ qua (trùng): ${skipped} địa điểm.`);

  // Đếm lại tổng số địa điểm theo từng tỉnh
  const stats = await prisma.place.groupBy({
    by: ['province'],
    _count: { id: true },
    orderBy: { _count: { id: 'desc' } },
  });

  console.log('\n📊 THỐNG KÊ TỔNG ĐỊA ĐIỂM TRONG DATABASE HIỆN TẠI:');
  for (const s of stats) {
    console.log(` - ${s.province}: ${s._count.id} địa điểm`);
  }

  const totalAll = await prisma.place.count();
  console.log(`\n🔥 TỔNG CỘNG TOÀN DATABASE: ${totalAll} ĐỊA ĐIỂM!`);
}

main()
  .catch((e) => {
    console.error('❌ Lỗi seed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
